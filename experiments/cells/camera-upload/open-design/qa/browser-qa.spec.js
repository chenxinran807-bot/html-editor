const {test,expect}=require('./runtime/node_modules/@playwright/test');
const fs=require('fs');
const path=require('path');
const OUT=__dirname;
test.use({viewport:{width:390,height:844},launchOptions:{executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'}});
test('camera upload fixed tasks',async({page})=>{
  const startedAt=new Date(); const consoleErrors=[]; const pageErrors=[]; const taskAssertions=[];
  const mark=(id,details)=>taskAssertions.push({id,pass:true,details,at:new Date().toISOString()});
  page.on('console',m=>{if(m.type()==='error')consoleErrors.push(m.text())});
  page.on('pageerror',e=>pageErrors.push(String(e)));
  await page.goto('http://127.0.0.1:8289/opendesign/mockups/camera-upload/index.html');
  await page.evaluate(()=>localStorage.clear()); await page.reload();
  await expect(page.locator('link[href*="colors_and_type.css"]')).toHaveCount(1);
  await expect(page.locator('.phone')).not.toContainText('/front/');
  await page.screenshot({path:path.join(OUT,'screenshots/01-entry.png'),fullPage:true});
  await page.getByRole('button',{name:'关闭创建形象'}).click();
  await expect(page.getByTestId('open-creator')).toBeVisible();
  await page.getByTestId('open-creator').click();
  await page.getByTestId('open-policy').click();
  await expect(page.getByTestId('policy-dialog')).toBeVisible();
  await page.screenshot({path:path.join(OUT,'screenshots/02-policy-dialog.png'),fullPage:true});
  await page.getByRole('button',{name:'关闭用户协议'}).click();
  await page.getByTestId('open-upload').click();
  await expect(page.getByTestId('upload-choices')).toContainText('拍照');
  await expect(page.getByTestId('upload-choices')).toContainText('从相册选择');
  mark('open-upload-choices','camera and album choices visible');
  await page.screenshot({path:path.join(OUT,'screenshots/03-upload-choices.png'),fullPage:true});
  await page.getByTestId('camera-choice').click();
  await expect(page.locator('.phone')).toHaveAttribute('data-screen','camera');
  mark('enter-camera','capture screen active');
  await page.getByTestId('flip-camera').click();
  await expect(page.locator('.phone')).toHaveAttribute('data-facing','rear');
  mark('flip-camera','facing changed to rear');
  await page.screenshot({path:path.join(OUT,'screenshots/04-camera-flipped.png'),fullPage:true});
  await page.getByTestId('open-album').click();
  await expect(page.getByTestId('album-state')).toBeVisible();
  mark('open-album','album selection visible');
  await page.screenshot({path:path.join(OUT,'screenshots/05-album.png'),fullPage:true});
  await page.getByRole('button',{name:'‹'}).click();
  await page.getByTestId('close-camera').click();
  await expect(page.getByTestId('upload-choices')).toBeVisible();
  mark('close-camera','returned to upload choices');
  await page.getByTestId('camera-choice').click();
  await expect(page.locator('.phone')).toHaveAttribute('data-facing','rear');
  await page.getByTestId('shutter').click();
  await expect(page.getByTestId('retake')).toBeVisible();
  mark('shutter','photo confirmation visible');
  await page.screenshot({path:path.join(OUT,'screenshots/06-photo-confirmation.png'),fullPage:true});
  await page.getByTestId('retake').click();
  await expect(page.locator('.phone')).toHaveAttribute('data-screen','camera');
  mark('retake','capture screen restored with facing preserved');
  await page.getByTestId('shutter').click();
  await page.getByTestId('use-photo').click();
  await expect(page.getByTestId('review-loading')).toBeVisible();
  mark('use-photo','review loading visible');
  await page.screenshot({path:path.join(OUT,'screenshots/07-review-loading.png'),fullPage:true});
  await expect(page.getByTestId('review-result')).toContainText('不符合规范',{timeout:3000});
  mark('review-failure','failure guidance visible');
  await page.screenshot({path:path.join(OUT,'screenshots/08-review-failure.png'),fullPage:true});
  await page.getByTestId('retry').click();
  await expect(page.getByTestId('upload-choices')).toBeVisible();
  mark('retry','upload choices restored');
  await page.getByTestId('album-choice').click();
  await page.getByRole('button',{name:'选择合规照片'}).click();
  await expect(page.getByTestId('use-photo')).toBeVisible();
  await page.getByTestId('use-photo').click();
  await expect(page.getByTestId('review-result')).toContainText('上传成功',{timeout:3000});
  await page.screenshot({path:path.join(OUT,'screenshots/09-review-success.png'),fullPage:true});
  const finishedAt=new Date();
  const raw={url:page.url(),browserVersion:await page.context().browser().version(),viewport:{width:390,height:844},startedAt:startedAt.toISOString(),finishedAt:finishedAt.toISOString(),durationMs:finishedAt-startedAt,taskAssertions,persistence:{facingAfterReturn:'rear'},consoleErrors,pageErrors};
  fs.writeFileSync(path.join(OUT,'browser-qa-raw.json'),JSON.stringify(raw,null,2));
  expect(taskAssertions).toHaveLength(10);
  expect(consoleErrors).toEqual([]); expect(pageErrors).toEqual([]);
});

test('larger mobile viewport remains usable',async({page})=>{
  await page.setViewportSize({width:430,height:900});
  await page.goto('http://127.0.0.1:8289/opendesign/mockups/camera-upload/index.html');
  await page.evaluate(()=>localStorage.clear()); await page.reload();
  await expect(page.getByTestId('open-upload')).toBeVisible();
  await page.screenshot({path:path.join(OUT,'screenshots/10-viewport-430x900.png'),fullPage:true});
});
