const {test,expect}=require('./runtime/node_modules/@playwright/test');
const fs=require('fs');
const path=require('path');
const OUT=__dirname;
test.use({viewport:{width:390,height:844},launchOptions:{executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'}});
test('camera upload fixed tasks',async({page})=>{
  const consoleErrors=[]; const pageErrors=[];
  page.on('console',m=>{if(m.type()==='error')consoleErrors.push(m.text())});
  page.on('pageerror',e=>pageErrors.push(String(e)));
  await page.goto('http://127.0.0.1:8289/opendesign/mockups/camera-upload/index.html');
  await page.evaluate(()=>localStorage.clear()); await page.reload();
  await page.screenshot({path:path.join(OUT,'screenshots/01-entry.png'),fullPage:true});
  await page.getByTestId('open-upload').click();
  await expect(page.getByTestId('upload-choices')).toContainText('拍照');
  await expect(page.getByTestId('upload-choices')).toContainText('从相册选择');
  await page.screenshot({path:path.join(OUT,'screenshots/02-upload-choices.png'),fullPage:true});
  await page.getByTestId('camera-choice').click();
  await expect(page.locator('.phone')).toHaveAttribute('data-screen','camera');
  await page.getByTestId('flip-camera').click();
  await expect(page.locator('.phone')).toHaveAttribute('data-facing','rear');
  await page.getByTestId('open-album').click();
  await expect(page.getByTestId('album-state')).toBeVisible();
  await page.getByRole('button',{name:'‹'}).click();
  await page.getByTestId('close-camera').click();
  await expect(page.getByTestId('upload-choices')).toBeVisible();
  await page.getByTestId('camera-choice').click();
  await expect(page.locator('.phone')).toHaveAttribute('data-facing','rear');
  await page.getByTestId('shutter').click();
  await expect(page.getByTestId('retake')).toBeVisible();
  await page.screenshot({path:path.join(OUT,'screenshots/03-photo-confirmation.png'),fullPage:true});
  await page.getByTestId('retake').click();
  await expect(page.locator('.phone')).toHaveAttribute('data-screen','camera');
  await page.getByTestId('shutter').click();
  await page.getByTestId('use-photo').click();
  await expect(page.getByTestId('review-loading')).toBeVisible();
  await expect(page.getByTestId('review-result')).toContainText('不符合规范',{timeout:3000});
  await page.screenshot({path:path.join(OUT,'screenshots/04-review-failure.png'),fullPage:true});
  await page.getByTestId('retry').click();
  await expect(page.getByTestId('upload-choices')).toBeVisible();
  await page.getByTestId('album-choice').click();
  await page.getByRole('button',{name:'选择照片 1'}).click();
  await expect(page.getByTestId('use-photo')).toBeVisible();
  const raw={url:page.url(),tasks:{openUploadChoices:true,enterCamera:true,flipCamera:true,openAlbum:true,closeCamera:true,shutter:true,retake:true,usePhoto:true,reviewFailure:true,retry:true},persistence:{facingAfterReturn:'rear'},consoleErrors,pageErrors,finishedAt:new Date().toISOString()};
  fs.writeFileSync(path.join(OUT,'browser-qa-raw.json'),JSON.stringify(raw,null,2));
  expect(consoleErrors).toEqual([]); expect(pageErrors).toEqual([]);
});
